void main() {
  group('Online learning sync', () {
    const tenantId = 'tenant_alpha';

    late AppLocalDatabase database;
    late TenantContext tenantContext;

    setUp(() {
      database = AppLocalDatabase(executor: NativeDatabase.memory());
      tenantContext = TenantContext()
        ..setTenant(
          tenantId: tenantId,
          tenantName: 'Alpha School',
          role: 'school_owner',
          isSuperAdmin: false,
        );
    });

    tearDown(() async {
      await database.close();
    });

    test(
      'pull sync ingests tenant items, applies tombstones, and updates checkpoint',
      () async {
        await database.upsertOnlineLearningItemRecord(
          itemId: 'item_old',
          tenantId: tenantId,
          itemType: 'course',
          title: 'Old Course',
          source: 'local',
          updatedAt: DateTime.utc(2026, 8, 1, 8),
        );

        final gateway = _OnlineLearningGateway(
          itemRecords: [
            {
              'item_id': 'item_1',
              'tenant_id': tenantId,
              'item_type': 'course',
              'title': 'Modern Physics',
              'summary': 'Recorded lessons',
              'instructor_name': 'Dr. Das',
              'duration_label': '6h',
              'access_level': 'premium',
              'price_amount': 199,
              'published_at': DateTime.utc(2026, 8, 2).toIso8601String(),
              'is_active': true,
              'source': 'remote',
              'updated_at': DateTime.utc(2026, 8, 2, 8).toIso8601String(),
            },
            {
              'item_id': 'item_other',
              'tenant_id': 'tenant_other',
              'title': 'Ignore',
              'updated_at': DateTime.utc(2026, 8, 2, 9).toIso8601String(),
            },
            {
              'item_id': 'item_old',
              'tenant_id': tenantId,
              'operation': 'delete',
              'updated_at': DateTime.utc(2026, 8, 2, 10).toIso8601String(),
            },
          ],
        );

        final syncEngine = SyncEngine(
          database: database,
          pocketbaseGateway: gateway,
          tenantContext: tenantContext,
        );

        await syncEngine.manualSync();

        final rows = await database
            .watchOnlineLearningItems(tenantId: tenantId)
            .first;
        expect(rows.length, 1);
        expect(rows.single.id, 'item_1');
        expect(rows.single.title, 'Modern Physics');

        final deleted = await database.getEntityUpdatedAt(
          entityType: 'online_learning_item',
          tenantId: tenantId,
          entityId: 'item_old',
        );
        expect(deleted, isNull);

        final otherTenant = await database.getEntityUpdatedAt(
          entityType: 'online_learning_item',
          tenantId: 'tenant_other',
          entityId: 'item_other',
        );
        expect(otherTenant, isNull);

        final checkpoint = await database.getLastPullCheckpoint(
          'online_learning_item',
        );
        expect(checkpoint, isNotNull);
      },
    );
  });
}
