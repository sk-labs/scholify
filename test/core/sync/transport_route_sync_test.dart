void main() {
  group('Transport route sync', () {
    const tenantId = 'tenant_alpha';

    late AppLocalDatabase database;
    late TenantContext tenantContext;

    setUp(() {
      database = AppLocalDatabase(executor: NativeDatabase.memory());
      tenantContext = TenantContext()
        ..setTenant(
          tenantId: tenantId,
          tenantName: 'Alpha School',
          role: 'school_owner',
          isSuperAdmin: false,
        );
    });

    tearDown(() async {
      await database.close();
    });

    test(
      'pull sync ingests tenant transport routes, applies tombstones, and updates checkpoint',
      () async {
        await database.upsertTransportRouteRecord(
          routeId: 'route_old',
          tenantId: tenantId,
          routeTitle: 'Old Route',
          pickupPoint: 'Old Pickup',
          destinationPoint: 'Old Campus',
          source: 'local',
          updatedAt: DateTime.utc(2026, 6, 1, 8),
        );

        final gateway = _TransportRouteGateway(
          routeRecords: [
            {
              'route_id': 'route_1',
              'tenant_id': tenantId,
              'route_title': 'Morning Route',
              'vehicle_no': 'UP32 AB 1234',
              'driver_name': 'Ramesh',
              'pickup_point': 'Sector 4',
              'destination_point': 'Main Campus',
              'pickup_time': '07:20',
              'drop_time': '08:00',
              'monthly_fare': 1200,
              'is_active': true,
              'source': 'remote',
              'updated_at': DateTime.utc(2026, 6, 2, 8).toIso8601String(),
            },
            {
              'route_id': 'route_other',
              'tenant_id': 'tenant_other',
              'route_title': 'Ignore',
              'updated_at': DateTime.utc(2026, 6, 2, 9).toIso8601String(),
            },
            {
              'route_id': 'route_old',
              'tenant_id': tenantId,
              'operation': 'delete',
              'updated_at': DateTime.utc(2026, 6, 2, 10).toIso8601String(),
            },
          ],
        );

        final syncEngine = SyncEngine(
          database: database,
          pocketbaseGateway: gateway,
          tenantContext: tenantContext,
        );

        await syncEngine.manualSync();

        final rows = await database
            .watchTransportRoutes(tenantId: tenantId)
            .first;
        expect(rows.length, 1);
        expect(rows.single.id, 'route_1');
        expect(rows.single.routeTitle, 'Morning Route');

        final deleted = await database.getEntityUpdatedAt(
          entityType: 'transport_route',
          tenantId: tenantId,
          entityId: 'route_old',
        );
        expect(deleted, isNull);

        final otherTenant = await database.getEntityUpdatedAt(
          entityType: 'transport_route',
          tenantId: 'tenant_other',
          entityId: 'route_other',
        );
        expect(otherTenant, isNull);

        final checkpoint = await database.getLastPullCheckpoint(
          'transport_route',
        );
        expect(checkpoint, isNotNull);
      },
    );
  });
}
