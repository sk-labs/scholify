void main() {
  group('Tenant feature flag sync', () {
    const tenantId = 'tenant_alpha';

    late AppLocalDatabase database;
    late TenantContext tenantContext;

    setUp(() {
      database = AppLocalDatabase(executor: NativeDatabase.memory());
      tenantContext = TenantContext()
        ..setTenant(
          tenantId: tenantId,
          tenantName: 'Alpha School',
          role: 'school_owner',
          isSuperAdmin: false,
        );
    });

    tearDown(() async {
      await database.close();
    });

    test(
      'pull sync ingests tenant feature flags for active tenant only',
      () async {
        final gateway = _FeatureFlagGateway(
          flagRecords: [
            {
              'flag_id': 'ff_tenant_alpha_exams',
              'tenant_id': tenantId,
              'feature_key': 'exams',
              'is_enabled': true,
              'updated_at': DateTime.utc(2026, 5, 2, 9).toIso8601String(),
              'source': 'remote',
            },
            {
              'flag_id': 'ff_tenant_other_exams',
              'tenant_id': 'tenant_other',
              'feature_key': 'exams',
              'is_enabled': false,
              'updated_at': DateTime.utc(2026, 5, 2, 10).toIso8601String(),
              'source': 'remote',
            },
          ],
        );

        final syncEngine = SyncEngine(
          database: database,
          pocketbaseGateway: gateway,
          tenantContext: tenantContext,
        );

        await syncEngine.manualSync();

        final rows = await database
            .watchTenantFeatureFlags(tenantId: tenantId)
            .first;
        expect(rows.length, 1);
        expect(rows.single.featureKey, 'exams');
        expect(rows.single.isEnabled, isTrue);

        final checkpoint = await database.getLastPullCheckpoint(
          'tenant_feature_flag',
        );
        expect(checkpoint, isNotNull);

        final otherTenantFlag = await database.getEntityUpdatedAt(
          entityType: 'tenant_feature_flag',
          tenantId: 'tenant_other',
          entityId: 'ff_tenant_other_exams',
        );
        expect(otherTenantFlag, isNull);
      },
    );
  });
}
