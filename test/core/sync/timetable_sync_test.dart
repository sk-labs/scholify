void main() {
  group('Timetable sync', () {
    const tenantId = 'tenant_alpha';

    late AppLocalDatabase database;
    late TenantContext tenantContext;

    setUp(() {
      database = AppLocalDatabase(executor: NativeDatabase.memory());
      tenantContext = TenantContext()
        ..setTenant(
          tenantId: tenantId,
          tenantName: 'Alpha School',
          role: 'school_owner',
          isSuperAdmin: false,
        );
    });

    tearDown(() async {
      await database.close();
    });

    test(
      'pull sync ingests tenant timetable slots, applies tombstones, and updates checkpoint',
      () async {
        await database.upsertTimetableSlotRecord(
          slotId: 'slot_old',
          tenantId: tenantId,
          dayOfWeek: 'Monday',
          periodIndex: 1,
          subjectName: 'Old Subject',
          timeFrom: '08:30',
          timeTo: '09:10',
          source: 'local',
          updatedAt: DateTime.utc(2026, 5, 1, 8),
        );

        final gateway = _TimetableGateway(
          slotRecords: [
            {
              'slot_id': 'slot_1',
              'tenant_id': tenantId,
              'day_of_week': 'Monday',
              'period_index': 2,
              'subject_name': 'Science',
              'teacher_name': 'Ms. Khan',
              'room_no': 'B-202',
              'time_from': '09:20',
              'time_to': '10:00',
              'is_active': true,
              'source': 'remote',
              'updated_at': DateTime.utc(2026, 5, 2, 8).toIso8601String(),
            },
            {
              'slot_id': 'slot_other',
              'tenant_id': 'tenant_other',
              'day_of_week': 'Tuesday',
              'period_index': 1,
              'subject_name': 'Ignore',
              'updated_at': DateTime.utc(2026, 5, 2, 9).toIso8601String(),
            },
            {
              'slot_id': 'slot_old',
              'tenant_id': tenantId,
              'operation': 'delete',
              'updated_at': DateTime.utc(2026, 5, 2, 10).toIso8601String(),
            },
          ],
        );

        final syncEngine = SyncEngine(
          database: database,
          pocketbaseGateway: gateway,
          tenantContext: tenantContext,
        );

        await syncEngine.manualSync();

        final rows = await database
            .watchTimetableSlots(tenantId: tenantId)
            .first;
        expect(rows.length, 1);
        expect(rows.single.id, 'slot_1');
        expect(rows.single.subjectName, 'Science');

        final deleted = await database.getEntityUpdatedAt(
          entityType: 'timetable_slot',
          tenantId: tenantId,
          entityId: 'slot_old',
        );
        expect(deleted, isNull);

        final otherTenant = await database.getEntityUpdatedAt(
          entityType: 'timetable_slot',
          tenantId: 'tenant_other',
          entityId: 'slot_other',
        );
        expect(otherTenant, isNull);

        final checkpoint = await database.getLastPullCheckpoint(
          'timetable_slot',
        );
        expect(checkpoint, isNotNull);
      },
    );
  });
}
